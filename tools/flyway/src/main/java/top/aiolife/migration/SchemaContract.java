package top.aiolife.migration;

import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.SerializationFeature;
import java.nio.file.Files;
import java.nio.file.Path;
import java.sql.Connection;
import java.util.Map;

/** 由隔离 MySQL 执行迁移产生的结构契约，绑定 SQL 和校验器源码。 */
public record SchemaContract(int format, String schemaVersion, String mysqlVersion,
                             Map<String, String> sources, SchemaSnapshot schema, Map<String, String> toolSources) {
    public static final int FORMAT = 5;
    public static final ObjectMapper JSON = new ObjectMapper().enable(SerializationFeature.INDENT_OUTPUT);
    public static SchemaContract read(Path file, Path root) throws Exception {
        var contract = JSON.readValue(file.toFile(), SchemaContract.class);
        if (contract.format != FORMAT || contract.schemaVersion == null || contract.schemaVersion.isBlank())
            throw new IllegalArgumentException("Requires versioned v5 schema contract generated by Maven verify");
        contract.schema.validate();
        if (!MigrationProject.sources(root).equals(contract.sources))
            throw new IllegalArgumentException("Schema contract SQL or migration settings hashes differ; run Maven verify on this revision");
        SchemaSnapshot.Version.parse(contract.mysqlVersion);
        return contract;
    }
    public static void write(Path file, Path root, String version, Connection connection) throws Exception {
        Files.createDirectories(file.toAbsolutePath().getParent());
        JSON.writeValue(file.toFile(), new SchemaContract(FORMAT, version,
                SchemaSnapshot.rows(connection, "SELECT VERSION()").getFirst().getFirst(),
                MigrationProject.sources(root), SchemaSnapshot.read(connection), MigrationProject.toolSources(root)));
    }
    public void check(Connection connection) throws Exception {
        var issues = schema.differences(SchemaSnapshot.read(connection));
        if (!issues.isEmpty()) throw new IllegalStateException("Schema preflight failed:\n" + String.join("\n", issues));
    }
}
